#!/usr/bin/env python3
"""Generate src/db_tags.h.

The proxy emulates multiple Redis databases by prefixing every key with the
database number. To keep the original hash slot (and therefore make MOVE and
COPY between databases single-slot, atomic operations), the prefix also
contains a hash tag ``{tag}`` chosen so that::

    CRC16(tag) % 16384 == slot(original_key)

The hash tag only depends on the slot, so a single table of 16384 tags is
enough.  Tags are three base62 characters: 62**3 == 238328 combinations for
16384 slots (~14.5 candidates per slot), which is enough to cover every slot
(verified by this script).

The generated file is committed, so building the proxy does not require Python.
Run ``make db-tags`` from the src directory to regenerate it.
"""

import string
import sys

SLOTS = 16384
TAG_LEN = 3
ALPHABET = string.ascii_letters + string.digits


def crc16(data: bytes) -> int:
    crc = 0
    for byte in data:
        crc ^= byte << 8
        for _ in range(8):
            if crc & 0x8000:
                crc = ((crc << 1) ^ 0x1021) & 0xFFFF
            else:
                crc = (crc << 1) & 0xFFFF
    return crc


def gen_tags():
    tags = [None] * SLOTS
    missing = SLOTS
    for tup in _product(ALPHABET, TAG_LEN):
        tag = "".join(tup)
        slot = crc16(tag.encode()) % SLOTS
        if tags[slot] is None:
            tags[slot] = tag
            missing -= 1
            if missing == 0:
                break
    if missing:
        missing_slots = [i for i, t in enumerate(tags) if t is None]
        raise SystemExit(
            "ERROR: %d slot(s) have no tag, e.g. %s"
            % (missing, missing_slots[:10])
        )
    return tags


def _product(alphabet, length):
    if length == 0:
        yield ()
        return
    for c in alphabet:
        for rest in _product(alphabet, length - 1):
            yield (c,) + rest


def render(tags) -> str:
    out = [
        "/* Generated by utils/gen_db_tags.py -- do not edit by hand.",
        " *",
        " * DB_SLOT_TAGS[i] is a 3-character hash tag whose CRC16 modulo",
        " * 16384 is exactly i. Prefixing a key with the tag for its slot",
        " * keeps the key in the same cluster slot.",
        " *",
        " * Regenerate with: make db-tags",
        " */",
        "",
        "#ifndef __REDIS_CLUSTER_PROXY_DB_TAGS_H__",
        "#define __REDIS_CLUSTER_PROXY_DB_TAGS_H__",
        "",
        "#define DB_SLOT_TAGS_COUNT %d" % SLOTS,
        "#define DB_SLOT_TAG_LEN %d" % TAG_LEN,
        "",
        "static const char DB_SLOT_TAGS[DB_SLOT_TAGS_COUNT][DB_SLOT_TAG_LEN + 1] = {",
    ]
    line = "   "
    for i, tag in enumerate(tags):
        item = ' "%s",' % tag
        if len(line) + len(item) > 79:
            out.append(line)
            line = "   "
        line += item
    if line.strip():
        out.append(line)
    out.append("};")
    out.append("")
    out.append("#endif /* __REDIS_CLUSTER_PROXY_DB_TAGS_H__ */")
    out.append("")
    return "\n".join(out)


def main(argv):
    path = argv[1] if len(argv) > 1 else "db_tags.h"
    tags = gen_tags()
    with open(path, "w") as f:
        f.write(render(tags))
    print("Generated %s (%d tags)" % (path, len(tags)))


if __name__ == "__main__":
    main(sys.argv)
